//  Module 3 — Topic 2: Arithmetic Operators

// Arithmetic operators mathematical calculations ke liye use hote hain.

// ```text
// +   Addition
// -   Subtraction
// *   Multiplication
// /   Division
// %   Remainder / Modulo
// **  Power / Exponent
// ```

//  Small Examples

// ```js
// console.log(10 + 5); // 15
// console.log(10 - 5); // 5
// console.log(10 * 5); // 50
// console.log(10 / 5); // 2
// ```

//  `%` Modulo Operator

// `%` division ka **remainder** return karta hai.

// ```js
// console.log(10 % 3); // 1
// console.log(8 % 2);  // 0
// ```

// Practical use: number even ya odd check karna.

// ```js
// const number = 8;

// console.log(number % 2); // 0
// ```

// Agar remainder `0` ho to number even hai.

//  `**` Exponent Operator

// Power calculate karta hai:

// ```js
// console.log(2 ** 3); // 8
// ```

// Meaning:

// ```text
// 2 × 2 × 2 = 8
// ```

