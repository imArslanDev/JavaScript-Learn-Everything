// ## Module 3 — Topic 3: Assignment Operators

// Assignment operators variable mein value **assign ya update** karne ke liye use hote hain.

// ### Basic Assignment

// ```js
// let score = 10;
// ```

// Yahan:

// ```text
// = → Assignment Operator
// ```

// Matlab `10` ki value `score` mein assign karo.

// ### Compound Assignment Operators

// Long form:

// ```js
// let total = 100;
// total = total + 50;
// ```

// Shortcut:

// ```js
// total += 50;
// ```

// Dono ka result same:

// ```text
// 150
// ```

// Common operators:

// ```text
// =    Assign
// +=   Add and assign
// -=   Subtract and assign
// *=   Multiply and assign
// /=   Divide and assign
// %=   Remainder and assign
// **=  Power and assign
// ```

// ### Practical Example — Shopping Cart

// ```js
// let cartTotal = 500;

// cartTotal += 200;

// console.log(cartTotal); // 700
// ```

// User ne ek aur product add kiya, isliye existing total ko update kar diya.

// Another example:

// ```js
// let stock = 20;

// stock -= 3;

// console.log(stock); // 17
// ```

// 3 products sell hue, stock reduce ho gaya.

// ### Developer ko kya yaad rakhna hai?

