// # Module 3 — Topic 1: Operators & Operands

// ### Concept

// **Operator** ek symbol hota hai jo JavaScript ko batata hai ke values ke saath kya operation perform karna hai.

// ```js
// 5 + 3
// ```

// Yahan:

// ```text
// 5, 3 → operands
// +    → operator
// ```

// **Operands** woh values hain jin par operator kaam karta hai.

// JavaScript mein major operator categories hain:

// ```text
// Arithmetic
// Assignment
// Comparison
// Logical
// Increment / Decrement
// Ternary
// Bitwise
// ```

// Document bhi operators ko isi tarah categories mein divide karta hai.

// ### Practical Example

// Shopping cart:

// ```js
// const price = 500;
// const quantity = 3;

// const total = price * quantity;
// ```

// Yahan `*` multiplication operator hai aur `price`, `quantity` operands hain.

// ### Developer ko kya yaad rakhna hai?

// Simple rule:

// ```text
// Operands = data/values
// Operator = action on those values
// ```

