// Step 1 — Concept
// Variable ek named container hai jisme hum data store karte hain, taake baad mein us value ko use ya change kar saken.
// Example:
let price = 500;

// Yahan:
// . let → variable banane ka keyword
// . price → variable ka naam
// . 500 → stored value
// . = → assignment operator

// 3 Basic Stages of Variable:
let carName;              // Declaration
carName = "Honda Civic"; // Initialization / assignment
console.log(carName);   // Use

// But Usually Declaration + Initialization 1 sath hoti hain.
let myCar = "Ferari F80"

// Practical Usage
// Frontend: User ka entered username store karna:
let userName = "Arslan"

// Backend: Database se aayi product price temporarily store karna:
let productPrice = 200

